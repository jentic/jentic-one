// requireUnixPerms skips a test that asserts a POSIX permission bit. Windows
// carries only a read-only flag, so Go reports 0666/0444 there whatever mode
// was set.
func requireUnixPerms(t *testing.T) {
	t.Helper()
	if runtime.GOOS == "windows" {
		t.Skip("POSIX permission bits are not represented on Windows")
	}
}

// A compose file in the shape the template renders: a database service on its
// own image, and app + broker sharing the app image. The database image is the
// constant the template really renders, so the assertion that a repoint leaves
// it alone is pinned against what ships rather than a hand-typed tag.
const composeFixture = `# Generated by 'jenticctl install'.
name: jentic
services:
  db:
    image: %[2]s
    environment:
      POSTGRES_DB: "jentic"
  app:
    image: %[1]s
    environment:
      JENTIC_CONFIG_FILE: /etc/jentic/jentic-one.yaml
  broker:
    image: %[1]s
    environment:
      JENTIC_CONFIG_FILE: /etc/jentic/jentic-one.yaml
`

func writeCompose(t *testing.T, image string) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "docker-compose.yaml")
	body := strings.ReplaceAll(composeFixture, "%[1]s", image)
	body = strings.ReplaceAll(body, "%[2]s", postgresImage)
	if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
		t.Fatalf("write compose: %v", err)
	}
	return path
}

// A pulled install's compose file reports the published reference; a
// from-source one reports the fixed local tag. That difference is what tells an
// update which way to refresh the stack.
func TestComposeAppImageReadsTheAppService(t *testing.T) {
	for _, image := range []string{"ghcr.io/jentic/jentic-one-app:0.43.0", AppImageTag} {
		got, err := ComposeAppImage(writeCompose(t, image))
		if err != nil {
			t.Fatalf("ComposeAppImage(%s): %v", image, err)
		}
		if got != image {
			t.Errorf("ComposeAppImage = %q, want %q", got, image)
		}
	}
}

