// Both services carrying the app image move together. Leaving one behind would
// run the app and the broker on different versions, applying migrations from
// one against a peer on the other.
func TestSetComposeAppImageMovesTheBrokerEvenWhenItDiffersFromTheApp(t *testing.T) {
	path := filepath.Join(t.TempDir(), "docker-compose.yaml")
	body := "services:\n" +
		"  app:\n    image: ghcr.io/jentic/jentic-one-app:0.43.0\n" +
		"  broker:\n    image: ghcr.io/jentic/jentic-one-app:0.42.0\n"
	if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
		t.Fatalf("write compose: %v", err)
	}

	if _, err := SetComposeAppImage(path, "ghcr.io/jentic/jentic-one-app:0.44.0"); err != nil {
		t.Fatalf("SetComposeAppImage: %v", err)
	}

	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read back: %v", err)
	}
	if n := strings.Count(string(raw), "image: ghcr.io/jentic/jentic-one-app:0.44.0"); n != 2 {
		t.Errorf("new image appears %d times, want 2 — the broker was left behind:\n%s", n, raw)
	}
}

// A line outside `services:` that happens to carry the same value — an `x-`
// extension documenting the image — is not a service and must not be rewritten.
func TestSetComposeAppImageLeavesNonServiceBlocksAlone(t *testing.T) {
	path := filepath.Join(t.TempDir(), "docker-compose.yaml")
	body := "x-app-defaults:\n  image: ghcr.io/jentic/jentic-one-app:0.43.0\n" +
		"services:\n  app:\n    image: ghcr.io/jentic/jentic-one-app:0.43.0\n"
	if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
		t.Fatalf("write compose: %v", err)
	}

	if _, err := SetComposeAppImage(path, "ghcr.io/jentic/jentic-one-app:0.44.0"); err != nil {
		t.Fatalf("SetComposeAppImage: %v", err)
	}

	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read back: %v", err)
	}
	got := string(raw)
	if n := strings.Count(got, "image: ghcr.io/jentic/jentic-one-app:0.43.0"); n != 1 {
		t.Errorf("the x- extension block was rewritten:\n%s", got)
	}
	if n := strings.Count(got, "image: ghcr.io/jentic/jentic-one-app:0.44.0"); n != 1 {
		t.Errorf("the app service was not moved exactly once:\n%s", got)
	}
}

// An operator who widened the compose file's mode (a shared ops group) keeps
// it: a repoint must not quietly narrow the file back to 0600.
func TestSetComposeAppImageKeepsAWidenedMode(t *testing.T) {
	requireUnixPerms(t)
	path := writeCompose(t, "ghcr.io/jentic/jentic-one-app:0.43.0")
	if err := os.Chmod(path, 0o640); err != nil {
		t.Fatalf("chmod: %v", err)
	}

	if _, err := SetComposeAppImage(path, "ghcr.io/jentic/jentic-one-app:0.44.0"); err != nil {
		t.Fatalf("SetComposeAppImage: %v", err)
	}

	info, err := os.Stat(path)
	if err != nil {
		t.Fatalf("stat: %v", err)
	}
	if got := info.Mode().Perm(); got != 0o640 {
		t.Errorf("mode = %v, want 0640 preserved", got)
	}
}

// A YAML alias holds its value at the anchor, not on the service's line, so a
// line-scoped rewrite cannot move it: say so instead of silently missing it.
func TestSetComposeAppImageRefusesAnAlias(t *testing.T) {
	path := filepath.Join(t.TempDir(), "docker-compose.yaml")
	body := "x-img: &app_image ghcr.io/jentic/jentic-one-app:0.43.0\n" +
		"services:\n  app:\n    image: *app_image\n"
	if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
		t.Fatalf("write compose: %v", err)
	}
	if _, err := SetComposeAppImage(path, "ghcr.io/jentic/jentic-one-app:0.44.0"); err == nil {
		t.Error("SetComposeAppImage = nil error, want a refusal naming the alias")
	}
}

// A service whose image merely STARTS WITH the app's — a debug sidecar beside
// the app's own tag — must not be rewritten into a tag that does not exist.
func TestSetComposeAppImageLeavesAPrefixMatchingSidecarAlone(t *testing.T) {
	path := filepath.Join(t.TempDir(), "docker-compose.yaml")
	body := "services:\n" +
		"  app:\n    image: ghcr.io/jentic/jentic-one-app:0.43.0\n" +
		"  debug:\n    image: ghcr.io/jentic/jentic-one-app:0.43.0-debug\n"
	if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
		t.Fatalf("write compose: %v", err)
	}

	if _, err := SetComposeAppImage(path, "ghcr.io/jentic/jentic-one-app:0.44.0"); err != nil {
		t.Fatalf("SetComposeAppImage: %v", err)
	}

	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read back: %v", err)
	}
	got := string(raw)
	if !strings.Contains(got, "image: ghcr.io/jentic/jentic-one-app:0.43.0-debug") {
		t.Errorf("the sidecar's image was rewritten:\n%s", got)
	}
	if !strings.Contains(got, "image: ghcr.io/jentic/jentic-one-app:0.44.0\n") {
		t.Errorf("the app's image was not moved:\n%s", got)
	}
}

// A quoted or oddly spaced value is still matched, and its quoting survives —
// otherwise the repoint fails after a successful pull or build.
func TestSetComposeAppImageHandlesQuotedAndSpacedValues(t *testing.T) {
	for _, tc := range []struct{ name, line, want string }{
		{"double-quoted", `    image: "ghcr.io/jentic/jentic-one-app:0.43.0"`, `    image: "ghcr.io/jentic/jentic-one-app:0.44.0"`},
		{"single-quoted", `    image: 'ghcr.io/jentic/jentic-one-app:0.43.0'`, `    image: 'ghcr.io/jentic/jentic-one-app:0.44.0'`},
		// Only the value is replaced, so the line's own spacing survives.
		{"extra-spaces", "    image:   ghcr.io/jentic/jentic-one-app:0.43.0", "    image:   ghcr.io/jentic/jentic-one-app:0.44.0"},
		{"inline-comment", "    image: ghcr.io/jentic/jentic-one-app:0.43.0 # pinned by ops", "    image: ghcr.io/jentic/jentic-one-app:0.44.0 # pinned by ops"},
		{"crlf-line", "    image: ghcr.io/jentic/jentic-one-app:0.43.0\r", "    image: ghcr.io/jentic/jentic-one-app:0.44.0\r"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			path := filepath.Join(t.TempDir(), "docker-compose.yaml")
			if err := os.WriteFile(path, []byte("services:\n  app:\n"+tc.line+"\n"), 0o600); err != nil {
				t.Fatalf("write compose: %v", err)
			}
			if _, err := ComposeAppImage(path); err != nil {
				t.Fatalf("ComposeAppImage: %v", err)
			}
			if _, err := SetComposeAppImage(path, "ghcr.io/jentic/jentic-one-app:0.44.0"); err != nil {
				t.Fatalf("SetComposeAppImage: %v", err)
			}
			raw, err := os.ReadFile(path)
			if err != nil {
				t.Fatalf("read back: %v", err)
			}
			if !strings.Contains(string(raw), tc.want) {
				t.Errorf("rewrote to:\n%s\nwant a line %q", raw, tc.want)
			}
		})
	}
}

// The compose file holds operator edits and the managed database password and
// no update can regenerate it, so the repoint must not truncate in place: the
// replacement arrives whole, by rename, and keeps its 0600 mode.
func TestSetComposeAppImageWritesAtomicallyAndKeepsMode(t *testing.T) {
	requireUnixPerms(t)
	path := writeCompose(t, "ghcr.io/jentic/jentic-one-app:0.43.0")

	if _, err := SetComposeAppImage(path, "ghcr.io/jentic/jentic-one-app:0.44.0"); err != nil {
		t.Fatalf("SetComposeAppImage: %v", err)
	}

	info, err := os.Stat(path)
	if err != nil {
		t.Fatalf("stat: %v", err)
	}
	if got := info.Mode().Perm(); got != 0o600 {
		t.Errorf("mode = %v, want 0600", got)
	}
	// No temp file is left behind for the next read to trip over.
	entries, err := os.ReadDir(filepath.Dir(path))
	if err != nil {
		t.Fatalf("readdir: %v", err)
	}
	for _, e := range entries {
		if e.Name() != "docker-compose.yaml" {
			t.Errorf("stray file left in the install dir: %s", e.Name())
		}
	}
}
