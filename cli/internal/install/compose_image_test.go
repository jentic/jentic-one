package install

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// A compose file in the shape the template renders: a database service on its
// own image, and app + broker sharing the app image.
const composeFixture = `# Generated by 'jenticctl install'.
name: jentic
services:
  db:
    image: postgres:17-alpine
    environment:
      POSTGRES_DB: "jentic"
  app:
    image: %[1]s
    environment:
      JENTIC_CONFIG_FILE: /etc/jentic/jentic-one.yaml
  broker:
    image: %[1]s
    environment:
      JENTIC_CONFIG_FILE: /etc/jentic/jentic-one.yaml
`

func writeCompose(t *testing.T, image string) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "docker-compose.yaml")
	body := strings.ReplaceAll(composeFixture, "%[1]s", image)
	if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
		t.Fatalf("write compose: %v", err)
	}
	return path
}

// A pulled install's compose file reports the published reference; a
// from-source one reports the fixed local tag. That difference is what tells an
// update which way to refresh the stack.
func TestComposeAppImageReadsTheAppService(t *testing.T) {
	for _, image := range []string{"ghcr.io/jentic/jentic-one-app:0.43.0", AppImageTag} {
		got, err := ComposeAppImage(writeCompose(t, image))
		if err != nil {
			t.Fatalf("ComposeAppImage(%s): %v", image, err)
		}
		if got != image {
			t.Errorf("ComposeAppImage = %q, want %q", got, image)
		}
	}
}

// A missing compose file is not an error: there is simply nothing to read, and
// the caller falls back to building rather than guessing a registry tag.
func TestComposeAppImageMissingFileIsEmpty(t *testing.T) {
	got, err := ComposeAppImage(filepath.Join(t.TempDir(), "absent.yaml"))
	if err != nil || got != "" {
		t.Errorf("ComposeAppImage = (%q, %v), want (\"\", nil)", got, err)
	}
}

func TestComposeAppImageWithoutAnAppServiceIsEmpty(t *testing.T) {
	path := filepath.Join(t.TempDir(), "docker-compose.yaml")
	if err := os.WriteFile(path, []byte("services: {}\n"), 0o600); err != nil {
		t.Fatalf("write compose: %v", err)
	}
	got, err := ComposeAppImage(path)
	if err != nil || got != "" {
		t.Errorf("ComposeAppImage = (%q, %v), want (\"\", nil)", got, err)
	}
}

// Repointing moves app and broker together and leaves the database service —
// which renders its own image — alone.
func TestSetComposeAppImageMovesAppAndBrokerOnly(t *testing.T) {
	path := writeCompose(t, "ghcr.io/jentic/jentic-one-app:0.43.0")

	changed, err := SetComposeAppImage(path, "ghcr.io/jentic/jentic-one-app:0.44.0")
	if err != nil {
		t.Fatalf("SetComposeAppImage: %v", err)
	}
	if !changed {
		t.Error("changed = false, want true")
	}

	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read back: %v", err)
	}
	body := string(raw)
	if n := strings.Count(body, "image: ghcr.io/jentic/jentic-one-app:0.44.0"); n != 2 {
		t.Errorf("new image appears %d times, want 2 (app + broker):\n%s", n, body)
	}
	if strings.Contains(body, "0.43.0") {
		t.Errorf("old image survived:\n%s", body)
	}
	if !strings.Contains(body, "image: postgres:17-alpine") {
		t.Errorf("database image was rewritten:\n%s", body)
	}
	// The generated file's header and keys survive a repoint.
	if !strings.Contains(body, "# Generated by 'jenticctl install'.") {
		t.Errorf("comment lost:\n%s", body)
	}
	if got, err := ComposeAppImage(path); err != nil || got != "ghcr.io/jentic/jentic-one-app:0.44.0" {
		t.Errorf("ComposeAppImage after repoint = (%q, %v)", got, err)
	}
}

func TestSetComposeAppImageToTheSameValueIsANoOp(t *testing.T) {
	path := writeCompose(t, AppImageTag)
	before, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read: %v", err)
	}

	changed, err := SetComposeAppImage(path, AppImageTag)
	if err != nil {
		t.Fatalf("SetComposeAppImage: %v", err)
	}
	if changed {
		t.Error("changed = true, want false for an unchanged image")
	}
	after, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read back: %v", err)
	}
	if string(before) != string(after) {
		t.Error("a no-op repoint rewrote the file")
	}
}

// Repointing a compose file with no app image fails loudly rather than
// appending a service or silently doing nothing.
func TestSetComposeAppImageWithoutAnAppServiceErrors(t *testing.T) {
	path := filepath.Join(t.TempDir(), "docker-compose.yaml")
	if err := os.WriteFile(path, []byte("services: {}\n"), 0o600); err != nil {
		t.Fatalf("write compose: %v", err)
	}
	if _, err := SetComposeAppImage(path, AppImageTag); err == nil {
		t.Error("SetComposeAppImage = nil error, want a failure")
	}
}
